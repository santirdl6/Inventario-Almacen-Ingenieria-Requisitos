using System.Text.Json;
using Inventario.Api.Domain.MasterData;

namespace Inventario.Api.Domain.Purchasing;

public enum PurchaseOrderState { Draft, Sent, PartiallyReceived, Received }
public enum PurchaseSendStatus { None, Pending, Accepted, Failed }

public sealed record PurchaseSupplierSnapshot(Guid Id, string Code, string Name, string? Email,
    string? TaxIdentifier, int SchemaVersion = 1)
{
    public static PurchaseSupplierSnapshot From(Supplier supplier) =>
        new(supplier.Id, supplier.Code, supplier.Name, supplier.Email, supplier.TaxIdentifier);
}

public sealed class PurchaseOrder
{
    private readonly List<PurchaseOrderLine> lines = [];
    private PurchaseOrder() { }
    public Guid Id { get; private set; }
    public string Number { get; private set; } = null!; // Generated by the shared SQL sequence.
    public Guid SupplierId { get; private set; }
    public string SupplierSnapshot { get; private set; } = "";
    public string Currency { get; private set; } = "";
    public DateOnly ExpectedDeliveryDate { get; private set; }
    public PurchaseOrderState State { get; private set; }
    public PurchaseSendStatus SendStatus { get; private set; }
    public Guid CreatedBy { get; private set; }
    public DateTimeOffset CreatedAt { get; private set; }
    public DateTimeOffset? SentAt { get; private set; }
    public Guid RevisionStamp { get; private set; }
    public byte[] Version { get; private set; } = [];
    public IReadOnlyCollection<PurchaseOrderLine> Lines => lines;
    public bool IsEditable => State == PurchaseOrderState.Draft && SendStatus == PurchaseSendStatus.None;

    internal static PurchaseOrder Create(Guid id, PurchaseSupplierSnapshot supplier, string currency,
        DateOnly expected, Guid actor, IEnumerable<PurchaseOrderLine> content)
    {
        if (id == Guid.Empty || actor == Guid.Empty || supplier.Id == Guid.Empty)
            throw new ArgumentException("El pedido requiere identidades válidas.");
        if (currency.Length != 3 || currency.Any(value => value is < 'A' or > 'Z'))
            throw new ArgumentException("La moneda debe ser un código ISO de tres letras.");
        var order = new PurchaseOrder { Id = id, Currency = currency, CreatedBy = actor, CreatedAt = DateTimeOffset.UtcNow };
        order.Edit(supplier, expected, content);
        return order;
    }

    internal void Edit(PurchaseSupplierSnapshot supplier, DateOnly expected, IEnumerable<PurchaseOrderLine> content)
    {
        if (!IsEditable) throw new InvalidOperationException("El documento de compra está congelado.");
        var values = content.ToArray();
        if (values.Length == 0 || values.Any(line => line.PurchaseOrderId != Id)
            || values.Select(line => line.Id).Distinct().Count() != values.Length
            || values.Select(line => line.Position).Distinct().Count() != values.Length)
            throw new ArgumentException("El pedido requiere líneas propias e identidades y posiciones únicas.");
        if (SupplierId != supplier.Id)
            SupplierSnapshot = JsonSerializer.Serialize(supplier, PurchaseSnapshotJson.Options);
        SupplierId = supplier.Id;
        ExpectedDeliveryDate = expected;
        lines.Clear(); lines.AddRange(values);
        Touch();
    }

    internal void RequestSend()
    {
        if (!IsEditable) throw new InvalidOperationException("El envío ya se solicitó.");
        SendStatus = PurchaseSendStatus.Pending; Touch();
    }

    internal void RetrySend()
    {
        if (State != PurchaseOrderState.Draft || SendStatus != PurchaseSendStatus.Failed)
            throw new InvalidOperationException("Solo puede reintentarse un envío en error.");
        SendStatus = PurchaseSendStatus.Pending; Touch();
    }

    internal void FailSend()
    {
        if (SendStatus != PurchaseSendStatus.Pending || State != PurchaseOrderState.Draft)
            throw new InvalidOperationException("La solicitud ya no está pendiente.");
        SendStatus = PurchaseSendStatus.Failed; Touch();
    }

    internal void AcceptSend(DateTimeOffset acceptedAt)
    {
        if (SendStatus == PurchaseSendStatus.Accepted) return;
        if (SendStatus != PurchaseSendStatus.Pending || State != PurchaseOrderState.Draft)
            throw new InvalidOperationException("La aceptación no corresponde a una solicitud pendiente.");
        SendStatus = PurchaseSendStatus.Accepted; SentAt = acceptedAt.ToUniversalTime();
        DeriveReceiptState();
    }

    // HU-01 invokes this after changing received amounts in its own atomic confirmation.
    internal void DeriveReceiptState()
    {
        if (SendStatus != PurchaseSendStatus.Accepted)
        {
            if (lines.Any(line => line.ReceivedQuantity != 0))
                throw new InvalidOperationException("No se puede recibir una compra cuyo correo no está aceptado.");
            State = PurchaseOrderState.Draft;
        }
        else State = lines.All(line => line.PendingQuantity == 0) ? PurchaseOrderState.Received
            : lines.Any(line => line.ReceivedQuantity > 0) ? PurchaseOrderState.PartiallyReceived : PurchaseOrderState.Sent;
        Touch();
    }

    internal void Touch() => RevisionStamp = Guid.NewGuid();
}

internal static class PurchaseSnapshotJson
{
    public static readonly JsonSerializerOptions Options = new(JsonSerializerDefaults.Web);
}
