import { randomUUID } from 'node:crypto';
import { test, expect } from './fixtures/master-data.fixture';

test('historial real de inactivo conserva lotes, cantidades y autoría con filtros legibles por teclado', async ({ page, environment, gestor, historyData }) => {
  test.setTimeout(240_000);
  const familyResponse = await gestor.request.post('/api/v1/families', { headers: { 'X-XSRF-TOKEN': gestor.csrfToken, 'Idempotency-Key': randomUUID() }, data: { code: `HIST-${randomUUID()}`, name: 'Familia de historial real' } });
  expect(familyResponse.status()).toBe(201); const familyId = (await familyResponse.json()).resource.id;
  const sku = `LIFE-STOCK-${randomUUID()}`.toUpperCase();
  const response = await gestor.request.post('/api/v1/articles', { headers: { 'X-XSRF-TOKEN': gestor.csrfToken, 'Idempotency-Key': randomUUID() }, data: { sku, name: 'Artículo con historial real', familyId, baseUnit: 'KG', allowsFractional: true, tracksLot: true } });
  expect(response.status()).toBe(201); const id = (await response.json()).resource.id;
  const before = historyData('prepare', id);
  const history = await gestor.request.get(`/api/v1/articles/${id}/movements`);
  expect(history.status()).toBe(200); const original = await history.json(); expect(original.totalCount).toBe(3);
  await page.goto('/login'); await page.getByLabel('Correo electrónico (obligatorio)').fill(environment.accounts.gestor.email); await page.getByLabel('Contraseña (obligatoria)').fill(environment.accounts.gestor.password); await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
  await page.goto(`/maestros/articulos/${id}`);
  await expect(page.getByRole('button', { name: 'Eliminar artículo', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Desactivar en su lugar' }).click();
  const disabled = page.waitForResponse(value => value.url().endsWith(`/api/v1/articles/${id}`) && value.request().method() === 'PUT' && value.status() === 200);
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click(); await disabled;
  await page.goto('/maestros/articulos');
  await page.getByLabel('Código o nombre del artículo').fill(sku);
  await page.getByLabel('Estado del artículo').selectOption('inactive');
  await page.getByRole('button', { name: 'Buscar artículos', exact: true }).click();
  const match = page.getByRole('row').filter({ hasText: sku });
  await expect(match).toHaveCount(1);
  await match.getByRole('link', { name: 'Consultar artículo', exact: true }).click();
  await page.getByRole('link', { name: 'Consultar historial de movimientos' }).click();
  await expect(page.getByText('Inactivo', { exact: true })).toBeVisible();
  const table = page.getByRole('table', { name: 'Movimientos del artículo' });
  await expect(table.getByRole('row')).toHaveCount(4);
  await expect(table.getByText('Salida', { exact: true }).first()).toBeVisible();
  await expect(table.getByText('Recepción', { exact: true }).first()).toBeVisible();
  await expect(table.getByText('Contraparte E2E', { exact: false }).first()).toBeVisible();
  await page.getByLabel('Buscar responsable por nombre o código').fill(before.actorName);
  const actorSearch = page.waitForResponse(value => value.url().includes('/movements/filters?') && new URL(value.url()).searchParams.get('field') === 'actor');
  await page.getByRole('button', { name: 'Buscar responsables', exact: true }).click();
  expect((await actorSearch).status()).toBe(200);
  const actor = page.getByLabel('Responsable', { exact: true });
  await expect(actor.getByRole('option', { name: before.actorName, exact: true })).toBeAttached();
  await expect(actor).toBeEnabled(); await actor.focus(); await expect(actor).toBeFocused();
  await actor.pressSequentially(before.actorName); await actor.press('Tab');
  await expect(actor).toHaveValue(before.actorId);
  const row = original.items.find((item: { kind: string }) => item.kind === 'Shipment');
  await page.getByLabel('Ubicación', { exact: true }).selectOption(row.origin.id);
  await page.getByLabel('Lote', { exact: true }).selectOption(row.lot.id);
  await page.getByLabel('Desde (hora local)').fill('2020-01-01T00:00');
  await page.getByLabel('Hasta, sin incluir (hora local)').fill('2099-01-01T00:00');
  await page.getByRole('button', { name: 'Consultar movimientos', exact: true }).click();
  await expect(table.getByRole('row')).toHaveCount(3);
  await expect(table.getByText('2.125 KG', { exact: true })).toBeVisible();
  await expect(table.getByText('1.000 KG', { exact: true })).toBeVisible();
  await expect(table.getByText(before.actorName, { exact: true }).first()).toBeVisible();
  await expect(table.getByText('L-001', { exact: true }).first()).toBeVisible();
  await expect(table.getByText(row.origin.code, { exact: true }).first()).toBeVisible();
  await page.getByRole('link', { name: 'Volver al artículo', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Guardar artículo', exact: true })).toBeEnabled();
  await expect(page.getByLabel('Artículo activo', { exact: true })).not.toBeChecked();
  await page.getByLabel('Artículo activo', { exact: true }).check();
  await page.getByRole('button', { name: 'Guardar artículo', exact: true }).click();
  const reactivated = page.waitForResponse(value => value.url().endsWith(`/api/v1/articles/${id}`) && value.request().method() === 'PUT' && value.status() === 200);
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click(); await reactivated;
  expect(await (await gestor.request.get(`/api/v1/articles/${id}/movements`)).json()).toEqual(original);
  expect(historyData('snapshot', id)).toEqual(before);
});

test('artículo sin uso conserva historial al desactivar y reactivar, y permite borrado revisado', async ({ page, environment, gestor }) => {
  const familyResponse = await gestor.request.post('/api/v1/families', { headers: { 'X-XSRF-TOKEN': gestor.csrfToken, 'Idempotency-Key': randomUUID() }, data: { code: `LIFE-${randomUUID()}`, name: 'Familia retirada' } });
  expect(familyResponse.status()).toBe(201); const familyId = (await familyResponse.json()).resource.id;
  const sku = `LIFE-${randomUUID()}`.toUpperCase();
  const response = await gestor.request.post('/api/v1/articles', { headers: { 'X-XSRF-TOKEN': gestor.csrfToken, 'Idempotency-Key': randomUUID() }, data: { sku, name: 'Artículo sin referencias', familyId, baseUnit: 'UD', allowsFractional: false, tracksLot: false } });
  expect(response.status()).toBe(201); const id = (await response.json()).resource.id;
  await page.goto('/login'); await page.getByLabel('Correo electrónico (obligatorio)').fill(environment.accounts.gestor.email); await page.getByLabel('Contraseña (obligatoria)').fill(environment.accounts.gestor.password); await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
  await page.goto(`/maestros/articulos/${id}`); await expect(page.getByLabel('Código de artículo (obligatorio)')).toHaveValue(sku);
  await page.getByLabel('Artículo activo', { exact: true }).uncheck(); await page.getByRole('button', { name: 'Guardar artículo' }).click();
  const deactivated = page.waitForResponse(value => value.url().endsWith(`/api/v1/articles/${id}`) && value.request().method() === 'PUT' && value.status() === 200);
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click(); await deactivated;
  await page.getByRole('link', { name: 'Consultar historial de movimientos' }).click();
  await expect(page.getByText('Inactivo', { exact: true })).toBeVisible();
  await expect(page.getByText('No hay movimientos que coincidan con los filtros.')).toBeVisible();
  const movements = await gestor.request.get(`/api/v1/articles/${id}/movements`);
  expect(movements.status()).toBe(200);
  expect(await movements.json()).toMatchObject({ items: [], totalCount: 0 });
  await page.getByRole('link', { name: 'Volver al artículo', exact: true }).click();
  await expect(page.getByLabel('Código de artículo (obligatorio)')).toHaveValue(sku);
  const active = page.getByLabel('Artículo activo', { exact: true });
  await expect(active).not.toBeChecked();
  await active.check();
  await page.getByRole('button', { name: 'Guardar artículo' }).click();
  const reactivated = page.waitForResponse(value => value.url().endsWith(`/api/v1/articles/${id}`) && value.request().method() === 'PUT' && value.status() === 200);
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click(); await reactivated;
  await expect(page.getByText('Artículo guardado y confirmado.')).toBeVisible();
  const after = await gestor.request.get(`/api/v1/articles/${id}`);
  expect(await after.json()).toMatchObject({ isActive: true });
  await page.getByRole('button', { name: 'Eliminar artículo', exact: true }).click();
  await expect(page.getByText(/Dejará de aparecer en el catálogo/)).toContainText(sku);
  const deleted = page.waitForResponse(value => value.url().endsWith(`/api/v1/articles/${id}`) && value.request().method() === 'DELETE');
  await page.getByRole('button', { name: 'Eliminar definitivamente', exact: true }).click();
  const result = await deleted; expect(result.status()).toBe(204);
  await expect(page).toHaveURL(/\/maestros\/articulos$/);
  expect((await gestor.request.get(`/api/v1/articles/${id}`)).status()).toBe(404);
  const outcome = await gestor.request.get(`/api/v1/operations/${result.request().headers()['idempotency-key']}`);
  expect(outcome.status()).toBe(200); expect((await outcome.json()).status).toBe(204);
});
