import { randomUUID } from 'node:crypto';
import { test, expect } from './fixtures/master-data.fixture';

test('gestor mantiene contacto opcional, estados y duplicados de proveedor; lector solo consulta', async ({ page, environment, lector }) => {
  await page.goto('/login');
  await page.getByLabel('Correo electrónico (obligatorio)').fill(environment.accounts.gestor.email);
  await page.getByLabel('Contraseña (obligatoria)').fill(environment.accounts.gestor.password);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('link', { name: 'Proveedores', exact: true }).click();
  await page.getByRole('link', { name: 'Nuevo proveedor', exact: true }).click();
  const code = `PROV-${randomUUID()}`.toUpperCase();
  await page.getByLabel('Código de proveedor (obligatorio)').fill(code);
  await page.getByLabel('Nombre del proveedor (obligatorio)').fill('Proveedor de prueba');
  await expect(page.getByText(/Sin correo: puedes guardar/)).toBeVisible();
  await page.getByRole('button', { name: 'Guardar proveedor' }).click();
  await expect(page).toHaveURL(/\/maestros\/proveedores\/[0-9a-f-]+$/);
  const id = new URL(page.url()).pathname.split('/').at(-1)!;
  await page.getByLabel('Correo del proveedor (opcional)').fill('correo-invalido');
  await expect(page.getByRole('button', { name: 'Guardar proveedor' })).toBeDisabled();
  await page.getByLabel('Correo del proveedor (opcional)').fill('contacto@example.test');
  await page.getByLabel('Identificador fiscal (opcional)').fill('Referencia fiscal libre');
  await page.getByRole('button', { name: 'Guardar proveedor' }).click();
  await expect(page.getByText('Proveedor guardado y confirmado.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Guardar proveedor' })).toBeEnabled();
  await page.getByLabel('Proveedor activo', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Guardar proveedor' }).click();
  await expect(page.getByText(/Se conservan los documentos existentes;/)).toContainText(code);
  const saved = page.waitForResponse(response => response.url().endsWith(`/api/v1/suppliers/${id}`) && response.request().method() === 'PUT' && response.status() === 200);
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click(); await saved;
  await page.getByRole('link', { name: 'Volver a proveedores' }).click();
  await page.getByLabel('Código o nombre del proveedor').fill(code);
  await page.getByLabel('Estado del proveedor', { exact: true }).selectOption('inactive');
  await page.getByRole('button', { name: 'Buscar proveedores', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: code })).toContainText('Inactivo');
  expect((await (await lector.request.get(`/api/v1/suppliers/${id}`)).json()).email).toBe('contacto@example.test');
  const denied = await lector.request.put(`/api/v1/suppliers/${id}`, { headers: { 'X-XSRF-TOKEN': lector.csrfToken, 'Idempotency-Key': randomUUID() }, data: { code, name: 'No autorizado', isActive: true } });
  expect(denied.status()).toBe(403);
  await page.getByRole('link', { name: 'Nuevo proveedor', exact: true }).click();
  await page.getByLabel('Código de proveedor (obligatorio)').fill(code.toLowerCase());
  await page.getByLabel('Nombre del proveedor (obligatorio)').fill('No perder');
  await page.getByRole('button', { name: 'Guardar proveedor' }).click();
  await expect(page.getByText('Introduce un código libre.', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Nombre del proveedor (obligatorio)')).toHaveValue('No perder');
});
